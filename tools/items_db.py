#!/usr/bin/env python3
"""Generates mixins/ess-items/ess_items_db.rs from EssentialsX (GPL-3.0): the item alias database (items.json),
the enchantment aliases (Enchantments.java) and the potion effect aliases (Potions.java).

    python3 tools/items_db.py [--essentials ~/Projects/horizon-mods/EssentialsX]

items.json entries become (primary name, item path, extra, aliases): extra is "potion:<vanilla potion id>" for
potions (`strong_`/`long_` prefixes for upgraded/extended), "entity:<entity id>" for spawners, else "". The
`minecraft:<name>` aliases are dropped (the item db strips that prefix itself)."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "mixins/ess-items/ess_items_db.rs"


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def items(ess: Path):
    text = (ess / "Essentials/src/main/resources/items.json").read_text()
    data = json.loads("\n".join(line for line in text.split("\n") if not line.startswith("#")))
    entries = {k: v for k, v in data.items() if isinstance(v, dict)}
    aliases = {}
    for k, v in data.items():
        if isinstance(v, str) and not k.startswith("minecraft:") and v in entries:
            aliases.setdefault(v, []).append(k)
    rows = []
    for name, v in entries.items():
        path = v["material"].lower()
        extra = ""
        if "potionData" in v:
            p = v["potionData"]
            pid = p["type"].lower()
            if p.get("upgraded"):
                pid = "strong_" + pid
            elif p.get("extended"):
                pid = "long_" + pid
            extra = "potion:" + pid
        elif "entity" in v:
            extra = "entity:" + v["entity"].lower()
        rows.append((name, path, extra, " ".join(sorted(aliases.get(name, [])))))
    return rows


def java_aliases(path: Path, kind: str):
    """(alias, vanilla id, primary) from a static {...} block of X.put("alias", CONST) lines."""
    src = path.read_text()
    consts = {}
    for m in re.finditer(r'final \w+ (\w+) = RegistryUtil\.valueOf\(\w+\.class, "\w+", "(\w+)"\);', src):
        consts[m.group(1)] = m.group(2).lower()
    for m in re.finditer(r'final \w+ (\w+) = \w+\.getByName\("(\w+)"\);', src):
        consts[m.group(1)] = m.group(2).lower()
    out = []
    for m in re.finditer(r'(\w+)\.put\("([^"]+)", ([\w.]+)\);', src):
        table, alias, value = m.groups()
        if value.startswith(kind + "."):
            vid = value.split(".", 1)[1].lower()
        elif value in consts:
            vid = consts[value]
        else:
            continue
        out.append((alias, vid, not table.startswith("ALIAS")))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--essentials", default=str(Path.home() / "Projects/horizon-mods/EssentialsX"))
    args = ap.parse_args()
    ess = Path(args.essentials).expanduser()
    java = ess / "Essentials/src/main/java/com/earth2me/essentials"
    rows = items(ess)
    enchants = java_aliases(java / "Enchantments.java", "Enchantment")
    potions = java_aliases(java / "Potions.java", "PotionEffectType")
    out = [
        "// GENERATED by tools/items_db.py from EssentialsX (GPL-3.0): items.json, Enchantments.java, Potions.java.",
        "// Do not edit by hand. `crate::game::ess_items_db`.",
        "",
        "/// items.json: (primary name, item path, extra (`potion:<id>` | `entity:<id>` | \"\"), space-separated aliases).",
        "pub static ITEMS: &[(&str, &str, &str, &str)] = &[",
    ]
    for r in rows:
        out.append("    (" + ", ".join(rust_str(x) for x in r) + "),")
    out.append("];")
    out.append("")
    out.append("/// Enchantments.java: (name, enchantment path, listed by /enchant (ENCHANTMENTS) or alias only).")
    out.append("pub static ENCHANTMENTS: &[(&str, &str, bool)] = &[")
    for a, v, p in enchants:
        out.append(f"    ({rust_str(a)}, {rust_str(v)}, {'true' if p else 'false'}),")
    out.append("];")
    out.append("")
    out.append("/// Potions.java: (name, effect path, listed by /potion (POTIONS) or alias only).")
    out.append("pub static POTION_EFFECTS: &[(&str, &str, bool)] = &[")
    for a, v, p in potions:
        out.append(f"    ({rust_str(a)}, {rust_str(v)}, {'true' if p else 'false'}),")
    out.append("];")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT}: {len(rows)} items, {len(enchants)} enchantment names, {len(potions)} potion names")


if __name__ == "__main__":
    main()
