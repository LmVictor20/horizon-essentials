// Generates horizon-essentials' data modules from an EssentialsX checkout (GPL-3.0, as this project):
//
//   cargo run -p ess-gen -- [ESSENTIALSX_DIR]     (default: the EssentialsX clone beside the main checkout)
//
// writes, in mixins/essentials/:
//   ess_meta.rs      every command (name, module, aliases, description, usage) and permission (default, children)
//                    from each module's plugin.yml
//   ess_messages.rs  messages_<locale>.properties as sorted (key, MiniMessage) tables
//   ess_defaults.rs  the default files EssentialsX writes on first start (config.yml, kits.yml, motd.txt...)
// Injected modules can't `include!` files, so the data lives in generated Rust.

use ess_standalone::game::ess_yaml;
use serde_json::Value;
use std::{collections::BTreeMap, fmt::Write as _, fs, path::Path, path::PathBuf};

const MODULES: [(&str, &str); 9] = [
    ("Essentials", "core"),
    ("EssentialsChat", "chat"),
    ("EssentialsSpawn", "spawn"),
    ("EssentialsProtect", "protect"),
    ("EssentialsAntiBuild", "antibuild"),
    ("EssentialsDiscord", "discord"),
    ("EssentialsDiscordLink", "discordlink"),
    ("EssentialsXMPP", "xmpp"),
    ("EssentialsGeoIP", "geoip"),
];

/// The core files written on first start (name in the data folder, path under Essentials/src/main/resources).
const CORE_DEFAULTS: [&str; 10] =
    ["config.yml", "kits.yml", "worth.yml", "tpr.yml", "motd.txt", "rules.txt", "info.txt", "book.txt", "custom.txt", "custom_items.yml"];

const HEADER: &str = "// @generated by tools/ess-gen from EssentialsX (GPL-3.0). Do not edit: rerun `cargo run -p ess-gen`.\n";

fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn read(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn as_list(v: Option<&Value>) -> Vec<String> {
    match v {
        Some(Value::Array(a)) => a.iter().filter_map(|x| x.as_str().map(str::to_lowercase)).collect(),
        Some(Value::String(s)) => s.split(',').map(|s| s.trim().to_lowercase()).filter(|s| !s.is_empty()).collect(),
        _ => Vec::new(),
    }
}

fn meta(ess: &Path) -> String {
    let mut commands = String::new();
    let mut permissions: BTreeMap<String, (String, Vec<(String, bool)>)> = BTreeMap::new();
    let mut count = 0;
    for (dir, module) in MODULES {
        let path = ess.join(dir).join("src/main/resources/plugin.yml");
        let yaml = ess_yaml::parse(&read(&path)).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        if let Some(Value::Object(cmds)) = yaml.get("commands") {
            for (name, def) in cmds {
                let aliases = as_list(def.get("aliases"));
                let description = def.get("description").and_then(Value::as_str).unwrap_or("");
                let usage = def.get("usage").and_then(Value::as_str).unwrap_or("");
                let _ = writeln!(
                    commands,
                    "    CommandMeta {{ name: {}, module: {}, aliases: &[{}], description: {}, usage: {} }},",
                    lit(&name.to_lowercase()),
                    lit(module),
                    aliases.iter().map(|a| lit(a)).collect::<Vec<_>>().join(", "),
                    lit(description),
                    lit(usage)
                );
                count += 1;
            }
        }
        if let Some(Value::Object(perms)) = yaml.get("permissions") {
            for (node, def) in perms {
                let default = match def.get("default") {
                    Some(Value::Bool(true)) => "True",
                    Some(Value::Bool(false)) => "False",
                    Some(Value::String(s)) if s.eq_ignore_ascii_case("true") => "True",
                    Some(Value::String(s)) if s.eq_ignore_ascii_case("false") => "False",
                    Some(Value::String(s)) if s.eq_ignore_ascii_case("not op") || s.eq_ignore_ascii_case("!op") => "NotOp",
                    _ => "Op",
                };
                let children = match def.get("children") {
                    Some(Value::Object(c)) => c.iter().map(|(k, v)| (k.to_lowercase(), v.as_bool().unwrap_or(true))).collect(),
                    _ => Vec::new(),
                };
                permissions.insert(node.to_lowercase(), (default.to_string(), children));
            }
        }
    }
    let mut out = String::from(HEADER);
    out.push_str("// Every EssentialsX command and permission node, from each module's plugin.yml.\n\n");
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum PermDefault {\n    Op,\n    True,\n    False,\n    NotOp,\n}\n\n");
    out.push_str("#[derive(Debug)]\npub struct CommandMeta {\n    pub name: &'static str,\n    pub module: &'static str,\n    pub aliases: &'static [&'static str],\n    pub description: &'static str,\n    pub usage: &'static str,\n}\n\n");
    out.push_str("#[derive(Debug)]\npub struct PermMeta {\n    pub node: &'static str,\n    pub default: PermDefault,\n    pub children: &'static [(&'static str, bool)],\n}\n\n");
    let _ = writeln!(out, "/// {count} commands, in plugin.yml order per module.\npub static COMMANDS: &[CommandMeta] = &[\n{commands}];\n");
    let _ = writeln!(out, "/// {} permission nodes, sorted by node (binary search).\npub static PERMISSIONS: &[PermMeta] = &[", permissions.len());
    for (node, (default, children)) in &permissions {
        let _ = writeln!(
            out,
            "    PermMeta {{ node: {}, default: PermDefault::{default}, children: &[{}] }},",
            lit(node),
            children.iter().map(|(c, b)| format!("({}, {b})", lit(c))).collect::<Vec<_>>().join(", ")
        );
    }
    out.push_str("];\n\npub fn command(name: &str) -> Option<&'static CommandMeta> {\n    COMMANDS.iter().find(|c| c.name == name)\n}\n\n");
    out.push_str("pub fn permission(node: &str) -> Option<&'static PermMeta> {\n    PERMISSIONS.binary_search_by(|p| p.node.cmp(node)).ok().map(|i| &PERMISSIONS[i])\n}\n");
    out
}

/// java.util.Properties: `key=value` / `key: value`, `\` line continuations, `\uXXXX` and `\:`-style escapes.
fn properties(text: &str) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let mut lines = text.lines();
    while let Some(line) = lines.next() {
        let trimmed = line.trim_start();
        if trimmed.is_empty() || trimmed.starts_with('#') || trimmed.starts_with('!') {
            continue;
        }
        let mut logical = trimmed.to_string();
        while logical.ends_with('\\') && !logical.ends_with("\\\\") {
            logical.pop();
            match lines.next() {
                Some(next) => logical.push_str(next.trim_start()),
                None => break,
            }
        }
        let mut key = String::new();
        let mut chars = logical.chars().peekable();
        while let Some(c) = chars.next() {
            match c {
                '\\' => {
                    if let Some(n) = chars.next() {
                        key.push(n);
                    }
                }
                '=' | ':' => break,
                c if c.is_whitespace() => {
                    while chars.peek().is_some_and(|c| c.is_whitespace()) {
                        chars.next();
                    }
                    if matches!(chars.peek(), Some('=') | Some(':')) {
                        chars.next();
                    }
                    break;
                }
                c => key.push(c),
            }
        }
        while chars.peek().is_some_and(|c| c.is_whitespace()) {
            chars.next();
        }
        let mut value = String::new();
        while let Some(c) = chars.next() {
            if c != '\\' {
                value.push(c);
                continue;
            }
            match chars.next() {
                Some('n') => value.push('\n'),
                Some('t') => value.push('\t'),
                Some('r') => value.push('\r'),
                Some('f') => value.push('\u{c}'),
                Some('u') => {
                    let hex: String = chars.by_ref().take(4).collect();
                    if let Some(ch) = u32::from_str_radix(&hex, 16).ok().and_then(char::from_u32) {
                        value.push(ch);
                    }
                }
                Some(other) => value.push(other),
                None => {}
            }
        }
        out.insert(key, value);
    }
    out
}

fn messages(ess: &Path) -> String {
    let dir = ess.join("Essentials/src/main/resources");
    let mut locales: Vec<(String, PathBuf)> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .filter_map(|e| e.ok())
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().to_string();
            let locale = if name == "messages.properties" {
                "root".to_string()
            } else {
                name.strip_prefix("messages_")?.strip_suffix(".properties")?.to_string()
            };
            Some((locale, e.path()))
        })
        .collect();
    locales.sort();
    // Every locale is ~110 KB of tables in the game crate: by default only the fallback and English are
    // built in; the others load at runtime from messages_<locale>.properties in the data folder.
    if std::env::var_os("ESS_ALL_LOCALES").is_none() {
        locales.retain(|(l, _)| matches!(l.as_str(), "root" | "en" | "en_GB"));
    }
    let mut out = String::from(HEADER);
    out.push_str("// EssentialsX's messages (MiniMessage text with {0}-style placeholders), one sorted table per locale.\n");
    out.push_str("// `root` is messages.properties, the fallback for every key.\n\n");
    let mut index = String::from("/// (locale, table) for every locale, `root` first.\npub static LOCALES: &[(&str, &[(&str, &str)])] = &[\n");
    let mut ordered: Vec<&(String, PathBuf)> = locales.iter().filter(|(l, _)| l == "root").collect();
    ordered.extend(locales.iter().filter(|(l, _)| l != "root"));
    for (locale, path) in ordered {
        let table = properties(&read(path));
        if table.is_empty() {
            continue;
        }
        let ident = format!("MESSAGES_{}", locale.to_uppercase().replace(['-', '.'], "_"));
        let _ = writeln!(out, "pub static {ident}: &[(&str, &str)] = &[");
        for (k, v) in &table {
            let _ = writeln!(out, "    ({}, {}),", lit(k), lit(v));
        }
        out.push_str("];\n\n");
        let _ = writeln!(index, "    ({}, {ident}),", lit(locale));
    }
    index.push_str("];\n");
    out.push_str(&index);
    out.push_str("\n/// A message from one table (binary search).\npub fn lookup(table: &[(&'static str, &'static str)], key: &str) -> Option<&'static str> {\n    table.binary_search_by(|(k, _)| (*k).cmp(key)).ok().map(|i| table[i].1)\n}\n\n");
    out.push_str("pub fn locale(name: &str) -> Option<&'static [(&'static str, &'static str)]> {\n    LOCALES.iter().find(|(l, _)| l.eq_ignore_ascii_case(name)).map(|(_, t)| *t)\n}\n");
    out
}

fn defaults(ess: &Path) -> String {
    let mut out = String::from(HEADER);
    out.push_str("// The files EssentialsX writes into its data folder on first start, by path in that folder.\n\n");
    out.push_str("pub static FILES: &[(&str, &str)] = &[\n");
    for name in CORE_DEFAULTS {
        let text = read(&ess.join("Essentials/src/main/resources").join(name));
        let _ = writeln!(out, "    ({}, {}),", lit(name), lit(&text));
    }
    for (dir, module) in MODULES.iter().skip(1) {
        let config = ess.join(dir).join("src/main/resources/config.yml");
        if config.exists() {
            let _ = writeln!(out, "    ({}, {}),", lit(&format!("{module}/config.yml")), lit(&read(&config)));
        }
    }
    out.push_str("];\n\npub fn file(name: &str) -> Option<&'static str> {\n    FILES.iter().find(|(n, _)| *n == name).map(|(_, t)| *t)\n}\n");
    out
}

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").canonicalize().expect("repository root");
    let ess = std::env::args().nth(1).map(PathBuf::from).unwrap_or_else(|| {
        // The EssentialsX clone beside the main checkout (also from a worktree in .worktrees/<name>).
        let common = std::process::Command::new("git")
            .args(["-C", root.to_str().unwrap_or("."), "rev-parse", "--path-format=absolute", "--git-common-dir"])
            .output()
            .expect("git");
        let common = PathBuf::from(String::from_utf8_lossy(&common.stdout).trim());
        common.parent().and_then(Path::parent).expect("main checkout").join("EssentialsX")
    });
    let out = root.join("mixins/essentials");
    for (name, text) in [("ess_meta.rs", meta(&ess)), ("ess_messages.rs", messages(&ess)), ("ess_defaults.rs", defaults(&ess))] {
        fs::write(out.join(name), text).unwrap_or_else(|e| panic!("{name}: {e}"));
        println!("wrote mixins/essentials/{name}");
    }
}
